"""
RETIRED (kept for provenance): Scheme A was applied on 2026-10-14 (see figures/FIGURE_NUMBERING.md; the check is figures/check_figure_numbering.py).
The inventory below describes the state BEFORE renumbering, so running this script now would overwrite figures/FIGURE_NUMBERING_AUDIT.md with
post-renumbering counts presented as a proposal. It therefore exits unless --force is given.

Inventory of figure-number references and proposed renumbering schemes (read-only; nothing is renumbered).

Run from the repository root:
    python figures/audit_figure_numbering.py

Scans the text files under figures/ (captions, tables, README/notes, plot/extract/build scripts) for references such as "Figure 3C", "Figures 4 and 5",
"Fig. 5" and "Supplementary Figure S2", counts them per file, and writes figures/FIGURE_NUMBERING_AUDIT.md with the two candidate mappings,
the references each would touch, the text drawn inside images that would need a replot, and the decision required. No file other than the audit
document is written.
"""

import re
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path("figures")
OUT = ROOT / "FIGURE_NUMBERING_AUDIT.md"
EXT = {".md", ".py"}
SKIP_PARTS = {"__pycache__", "data"}
SKIP_FILES = {"FIGURE_NUMBERING_AUDIT.md", "audit_figure_numbering.py"}

PAT_LIST = re.compile(r"\bFigures? ((?:S?\d[A-D]?(?:[–\-]|, | and | & )?)+)")
PAT_FIG = re.compile(r"\bFig\. (S?\d)")
TOKEN = re.compile(r"S?\d")


def refs(text):
    c = Counter()
    for m in PAT_LIST.finditer(text):
        for t in TOKEN.findall(m.group(1)):
            c[t] += 1
    for m in PAT_FIG.finditer(text):
        c[m.group(1)] += 1
    return c


def main():
    import sys
    if "--force" not in sys.argv:
        sys.exit("retired: Scheme A is applied (figures/FIGURE_NUMBERING.md); use figures/check_figure_numbering.py. Pass --force to regenerate the audit document anyway.")
    per_file = {}
    for p in sorted(ROOT.rglob("*")):
        if p.suffix not in EXT or p.name in SKIP_FILES or SKIP_PARTS & set(p.parts):
            continue
        c = refs(p.read_text(encoding="utf-8", errors="replace"))
        if c:
            per_file[p.as_posix()] = c
    tot = Counter()
    for c in per_file.values():
        tot.update(c)
    main_tot = {k: tot.get(k, 0) for k in "12345"}
    supp_tot = {k: tot.get(k, 0) for k in ("S1", "S2", "S3")}
    touch_a = sum(main_tot[k] for k in "2345")                 # scheme A: every reference to a main figure 2-5 changes (old Figure 1 refs are ambiguous)
    touch_b = main_tot["1"] + sum(supp_tot.values())            # scheme B: old Figure 1 + all supplementary-figure references change

    rows = [f"| `{f}` | " + ", ".join(f"{k}: {v}" for k, v in sorted(c.items())) + " |" for f, c in per_file.items()]
    md = [
        "# Figure numbering audit and proposed mapping (no renumbering applied)", "",
        "Generated by `figures/audit_figure_numbering.py` (read-only). **Decision needed before any renumbering.**", "",
        "## Current state and the inconsistency", "",
        "`FIGURE_CAPTIONS_DRAFT.md` drafts a *New Figure 1* (study overview) first and labels the existing design figure \"Figure 1 (current; becomes Figure 2 after "
        "renumbering)\" — but the existing performance figure is already \"Figure 2\". If the old Figure 1 becomes Figure 2, Figures 2–5 must also shift (Scheme A); otherwise the "
        "old Figure 1 has to move out of the main numbering (Scheme B). Table numbers are independent of figure numbers; only the \"linked figure\" cells and notes change.", "",
        "| Current label | Content | Scheme A (shift all main figures) | Scheme B (demote old Figure 1 to the supplement) |", "|---|---|---|---|",
        "| New Figure 1 | study overview | Figure 1 | Figure 1 |",
        "| Figure 1 (current) | design, information layers, RNA timing | **Figure 2** | **Supplementary Figure S1** |",
        "| Figure 2 | next-visit performance, layers A–D | **Figure 3** | Figure 2 |",
        "| Figure 3 (A–D) | RNA contribution A–C; train-selected pathway composite D | **Figure 4** | Figure 3 |",
        "| Figure 4 | survival | **Figure 5** | Figure 4 |",
        "| Figure 5 | pathway coefficients | **Figure 6** | Figure 5 |",
        "| Supp. Figure S1 | calibration | S1 | **S2** |",
        "| Supp. Figure S2 | geographic hold-out | S2 | **S3** |",
        "| Supp. Figure S3 | SHAP | S3 | **S4** |", "",
        "Linked-table cells that change: Table S1 (Figure 3C), S2 (Figure S1), S3 (Figure S3), S4 (Figure S2), S5 (Figure 4), S6 (Figure 2), Table 1 (Figures 1/4–5 mentions).", "",
        "## Reference inventory (counts of references per file)", "",
        f"Totals — main figures: " + ", ".join(f"Fig {k}: {v}" for k, v in main_tot.items()) + "; supplementary: " + ", ".join(f"{k}: {v}" for k, v in supp_tot.items()) + ". "
        f"\"Figure 1\" is ambiguous (new overview vs old design figure) and must be resolved by hand. References touched: Scheme A ≈ {touch_a} (+ old-Figure-1 references), "
        f"Scheme B ≈ {touch_b}.", "",
        "| File | References by figure number |", "|---|---|", *rows, "",
        "Also affected (names, not text): folders `figures/publication_redesign/Fig1…Fig5/`, files `figure3A_trainonly*.png` etc., `figures/data/Fig3ABC_trainonly`, "
        "`Fig3D_trainonly`, `Fig45_trainonly`, extractor names `fig3ABC_/fig3D_/fig45_trainonly_extract_data.py` and `figS_*`. These can keep their current names (they are working names; "
        "add a mapping line to the README) to avoid breaking script paths and hash records.", "",
        "## Text drawn inside images (needs a replot if the number changes)", "",
        "* `Fig5/figure5A_trainonly.png` legend and footnote: \"Figure 3D five-pathway family\", \"(Figure 3D family) is not concordant\".",
        "* `Fig5/figure5B_trainonly.png` footnote: \"Member of the Figure 3D five-pathway family\".",
        "* `fig1_new/figure1_new.{png,pdf,svg}` panel E: \"(CV; Fig. 5)\".",
        "* No figure number is drawn inside Figures 3A–C, 3D (title/captions only), 4A–B or S1A–B.", "",
        "## Recommendation", "",
        "Scheme A, because it follows the stated instruction (old Figure 1 becomes Figure 2) and keeps all content in the main text; it touches more references, so apply it in one "
        "scripted pass (mapping table above), replot the three images listed, update the linked-table cells, extend `figures/check_trainonly_captions.py` to the new numbers, and keep "
        "working file/folder names unchanged. Choose Scheme B only if the old design figure is to be moved to the supplement. **Not applied: awaiting your decision.**"]
    OUT.write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"files with references: {len(per_file)}; main totals {main_tot}; supplementary {supp_tot}; wrote {OUT}")


if __name__ == "__main__":
    main()
